package com.allday.sleep2skin_be.domain.report.dto;

/**
 * 종합 리포트(REP-09~11)의 수면 점수 추세 판정. {@code TriagePolicy}가 이 값을 매긴다.
 *
 * <p>트리아지 발동 조건의 절반("수면 목표는 달성했는데 특정 피부 지표만 정체")에서 <b>"수면
 * 목표"를 대신한다</b> — 이 서비스에 수면 목표값(B6)이 없어(2026-08-14 MVP 제외) 절대적인 달성
 * 여부 대신 <b>최근 3주의 추세</b>로 판단한다.
 */
public enum SleepTrend {

    /** 전반부·후반부 평균 차이가 임계값 미만 — 오르지도 내리지도 않았다. */
    STABLE,

    /** 후반부 평균이 전반부보다 임계값 이상 높다. */
    RISING,

    /** 후반부 평균이 전반부보다 임계값 이상 낮다. */
    FALLING,

    /** 유효 표본의 표준편차가 임계값 이상 — 오르내림이 커서 추세를 말할 수 없다. */
    VOLATILE,

    /** 유효 표본이 부족하거나 전반부·후반부 중 한쪽이 통째로 결측이다. */
    INSUFFICIENT_DATA

}
