package com.allday.sleep2skin_be.domain.skin.dto;

/**
 * 지표 점수의 등급 라벨 (prd.md §10.1 확정). <b>세 지표가 같은 구간을 쓴다.</b>
 *
 * <p>저장하지 않는다 — 점수에서 매번 계산한다. 저장하면 컷오프를 조정했을 때 과거 데이터만
 * 옛 기준으로 남아 같은 78점이 어제는 "보통" 오늘은 "안정"으로 보인다(erd.md §2 원칙 ①).
 *
 * <p><b>숫자가 클수록 좋다.</b> 이 방향이 뒤집히면 값 범위는 정상이라 어떤 검증에도 걸리지 않고
 * 화면 문구만 정반대로 나간다 — {@code DARK_CIRCLE}과 같은 종류의 함정이다.
 */
public enum SkinGrade {

    /** 0~25 — 피부 컨디션 저하 가능성이 높음. */
    RISK,

    /** 26~50 — 피부 컨디션 저하 가능성 있음. */
    CAUTION,

    /** 51~75 — 일반적인 수준. */
    NORMAL,

    /** 76~100 — 수면으로 인한 피부 영향이 낮음. */
    STABLE

}
